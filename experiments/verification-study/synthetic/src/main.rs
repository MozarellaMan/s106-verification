//! Synthetic falsification of `s106::accuracy`: see README.md.

mod generator;
mod metrics;
mod scenarios;

use std::fmt::Write as _;
use std::path::PathBuf;
use std::thread;

use anyhow::Result;
use clap::Parser;

use metrics::{BinRow, Row, replicate, summarise};

#[derive(Parser)]
struct Args {
    /// directory for scenarios.csv, cells.csv and summary.md
    #[arg(long, default_value = "results")]
    out: PathBuf,
    /// replications per scenario
    #[arg(long, default_value_t = 200)]
    reps: usize,
    /// replications for scenarios with 50 schemes
    #[arg(long, default_value_t = 200)]
    reps_s50: usize,
    /// run only scenarios whose name starts with this
    #[arg(long)]
    only: Option<String>,
    /// worker threads
    #[arg(long, default_value_t = 4)]
    threads: usize,
}

fn main() -> Result<()> {
    let args = Args::parse();
    std::fs::create_dir_all(&args.out)?;
    let grid: Vec<_> = scenarios::grid()
        .into_iter()
        .filter(|s| {
            args.only
                .as_ref()
                .is_none_or(|o| s.name.starts_with(o.as_str()))
        })
        .collect();

    let mut rows: Vec<Row> = vec![];
    let mut bins: Vec<BinRow> = vec![];
    for (i, sc) in grid.iter().enumerate() {
        let n = if sc.params.schemes >= 50 {
            args.reps_s50
        } else {
            args.reps
        };
        eprintln!("[{}/{}] {} ({n} replications)", i + 1, grid.len(), sc.name);
        // replications are independent, so split them over threads; each has its own seeded stream
        let mut reps: Vec<_> = thread::scope(|s| {
            let handles: Vec<_> = (0..args.threads.max(1))
                .map(|t| {
                    s.spawn(move || {
                        (t..n)
                            .step_by(args.threads.max(1))
                            .map(|r| (r, replicate(&sc.params, sc.seed, r as u64)))
                            .collect::<Vec<_>>()
                    })
                })
                .collect();
            handles
                .into_iter()
                .flat_map(|h| h.join().unwrap())
                .collect()
        });
        reps.sort_by_key(|(r, _)| *r);
        let reps: Vec<_> = reps.into_iter().map(|(_, r)| r).collect();
        let (row, b) = summarise(sc, &reps);
        rows.push(row);
        bins.extend(b);
    }

    write_csv(&args.out.join("scenarios.csv"), &rows)?;
    write_csv(&args.out.join("cells.csv"), &bins)?;
    std::fs::write(args.out.join("summary.md"), summary(&grid, &rows, &args))?;
    eprintln!("wrote {}", args.out.display());
    Ok(())
}

fn write_csv<T: serde::Serialize>(path: &std::path::Path, rows: &[T]) -> Result<()> {
    let mut w = csv::Writer::from_path(path)?;
    for r in rows {
        w.serialize(r)?;
    }
    w.flush()?;
    Ok(())
}

fn pct(x: f64) -> String {
    format!("{:.1}%", 100.0 * x)
}

fn opt_pct(x: Option<f64>) -> String {
    x.map_or("-".into(), pct)
}

fn summary(grid: &[scenarios::Scenario], rows: &[Row], args: &Args) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "# Synthetic falsification of `accuracy.rs`\n");
    let _ = writeln!(
        s,
        "Generated by `cargo run --release`; fixed seeds. {} replications per scenario, {} for scenarios with 50 schemes.\n",
        args.reps, args.reps_s50
    );
    let _ = writeln!(s, "## Scenario grid\n");
    let _ = writeln!(
        s,
        "| scenario | schemes | accuracy (claude/person/datahub) | K | shared corruption | hard share / drop | not_stated share | stage | what it tests |"
    );
    let _ = writeln!(s, "|---|---|---|---|---|---|---|---|---|");
    for (sc, r) in grid.iter().zip(rows) {
        let _ = writeln!(
            s,
            "| {} | {} | {} | {} | {} | {} / {} | {} | {} | {} |",
            r.scenario,
            r.schemes,
            r.nominal_acc,
            r.k,
            r.rho_shared,
            r.hard_share,
            r.delta,
            r.missing,
            r.stage,
            sc.what
        );
    }
    let _ = writeln!(s, "\n## Metrics\n");
    let _ = writeln!(
        s,
        "| scenario | reps | true a1 | mean a1_hat (sd) | bias a1 | coverage a1 | no est. | fits=false | gate pass | false-pass | power | bias a2 / a3 | coverage a2 / a3 | confirmed/rep | confirmed wrong | estimated wrong | all-agree-wrong cells (est./conf.) | their mean error (min) |"
    );
    let _ = writeln!(
        s,
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"
    );
    for r in rows {
        let _ = writeln!(
            s,
            "| {} | {} | {:.3} | {:.3} ({:.3}) | {:+.3} | {} | {} | {} | {} | {} | {} | {:+.3} / {:+.3} | {} / {} | {:.1} | {} ({}) | {} ({}) | {} ({}) / {} | {} ({}) |",
            r.scenario,
            r.reps,
            r.true_a1,
            r.mean_a1,
            r.sd_a1,
            r.bias_a1,
            pct(r.coverage_a1),
            pct(r.no_estimate),
            pct(r.fits_false),
            pct(r.gate_pass),
            opt_pct(r.false_pass),
            opt_pct(r.power),
            r.bias_a2,
            r.bias_a3,
            pct(r.coverage_a2),
            pct(r.coverage_a3),
            r.confirmed_per_rep,
            opt_pct(r.confirmed_wrong_share),
            r.confirmed_wrong,
            opt_pct(r.estimated_wrong_share),
            r.estimated_cells,
            r.allwrong_cells,
            r.allwrong_estimated,
            r.allwrong_confirmed,
            opt_pct(r.allwrong_error_mean),
            opt_pct(r.allwrong_error_min),
        );
    }
    if let Some(r) = rows.iter().find(|r| r.scenario == "S1") {
        let _ = writeln!(
            s,
            "\nS1 bootstrap diagnostic: lower bound mean {:.3}, sd {:.3}; lower > true a1 ({:.3}) in {} of replications; mean a1_hat - lower {:.3} overall, {} where lower > true.",
            r.mean_lower_a1,
            r.sd_lower_a1,
            r.true_a1,
            pct(r.lower_above_true_a1),
            r.mean_width_a1,
            r.mean_width_a1_above
                .map_or("-".into(), |w| format!("{w:.3}")),
        );
    }
    let _ = writeln!(s, "\n## Definitions\n");
    for d in [
        "true a1: the population accuracy of reader 1 (claude) on a random cell, including the effect of difficulty, shared corruption and stage; a2, a3 likewise for person and datahub.",
        "mean a1_hat (sd), bias a1: mean and standard deviation of the point estimate over replications, and mean minus true a1.",
        "coverage: share of replications whose lower bound is at most the true accuracy (target 97.5% or more).",
        "no est.: share of replications where no triplet formed; fits=false: share of the estimates with lower bound above 1.",
        "gate pass: share of replications where reader 1 passes the gate (fits and lower >= 0.90); false-pass applies when true a1 < 0.90, power when true a1 >= 0.95.",
        "confirmed/rep: mean number of cells per replication that the ledger would mark `confirmed` (all readers agree, gate passed, error <= 1%, a non-LLM reader among them).",
        "confirmed wrong: observed share of confirmed cells whose agreed reading is actually wrong, with the count of wrong ones in brackets (target <= 1%).",
        "estimated wrong: observed share wrong among `estimated` cells (all agree, gate passed), with the number of such cells in brackets.",
        "all-agree-wrong cells: cells where every reader agrees on a wrong reading and `error()` gave a figure, with how many of them reached `estimated` and `confirmed`; their mean error is the posterior error `error()` gave them, with the minimum in brackets.",
    ] {
        let _ = writeln!(s, "- {d}");
    }
    let _ = writeln!(
        s,
        "\nThe error-bin reliability table (observed wrong share per posterior-error bin, estimated cells only) is in `cells.csv`."
    );
    s
}
